  <h2>Meditation und Fokus</h2>
  <p>Meditation und Fokus wirken passiv: Je höher beide Skills sind, desto schneller regeneriert sich dein Mana. Meditation lässt sich zusätzlich auch aktiv einsetzen – dafür müssen die Hände des Magiers allerdings frei sein.</p>

  <h2>Der Zauberstab</h2>
  <p>Auf Nebelland gibt es zwei Wege, einen Zauber zu wirken. Der erste führt über den <strong>Zauberstab</strong>, den du in der Magierakademie erwerben kannst. Ein Doppelklick darauf öffnet das Magierbuch mit seinen Zirkeln und den darin enthaltenen Zaubern.</p>
  <ul>
    <li>Die Zirkel wählst du über die Zahlen oben rechts im Buch.</li>
    <li>Links stehen alle Zauber des gewählten Zirkels. Vor jedem Zauber findest du zwei Symbole.</li>
    <li>Das erste Symbol schlägt die Beschreibung des Zaubers auf; sie erscheint rechts unterhalb der Zahlen. Ein Klick auf das Siegel ganz unten rechts wirkt den beschriebenen Zauber.</li>
    <li>Schneller geht es mit dem zweiten Symbol in Form eines Minuszeichens: Es wirkt den Zauber direkt.</li>
  </ul>

  <h2>Die Zauberbefehle</h2>
  <p>Der zweite Weg sind die <strong>Zauberbefehle</strong>. Du findest sie im <a href="<?php echo e(url('zauber')); ?>">Zauberbuch</a> und gibst sie einfach wie gesprochenen Text ein. Möchtest du also einen Feuerball auf deinen Gegner schleudern, tippst du <span class="cmd">[feuerball</span>.</p>
