  <h2>Tipps für den Anfang</h2>
  <p>In jeder Stadt gibt es genau einen Händler. Er zahlt wenig und verlangt viel – doch in schweren Anfangszeiten kauft er Handwerkern einige einfache Gegenstände ab, damit sie sich über Wasser halten können. Was er annimmt, ändert sich regelmäßig. Auf Dauer lohnt sich aber vor allem der Handel mit anderen Spielern.</p>
