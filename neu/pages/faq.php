<div class="faq">
  <details>
    <summary>Warum hört mich niemand, wenn ich im Nebenzimmer stehe?</summary>
    <div class="faq__answer"><p>Wände gelten bei uns als akustische Grenze – egal, ob die Tür offen oder geschlossen ist. Mit den Befehlen <span class="cmd">[lsay</span> und <span class="cmd">[lemote</span> kannst du dich trotzdem bemerkbar machen.</p></div>
  </details>
  <details>
    <summary>Wie mache ich mich vor einer fremden Tür bemerkbar?</summary>
    <div class="faq__answer"><p>Mit <span class="cmd">[klopf</span>. Im ganzen Haus erscheint dann die Meldung, dass jemand an die Tür geklopft hat.</p></div>
  </details>
  <details>
    <summary>Warum lassen Monster keine Beute fallen?</summary>
    <div class="faq__answer"><p>Bei den meisten Monstern haben wir den Loot entfernt. Dafür stehen in ihrer Nähe meist verschlossene Truhen mit 10 bis 60 Dukaten. Um sie zu öffnen, brauchst du Dietriche – die bekommst du beim Tüftler oder beim Händler deines Vertrauens.</p></div>
  </details>
  <details>
    <summary>Ich habe kein Geld mehr für Dietriche. Was nun?</summary>
    <div class="faq__answer"><p>Neben dem Handel mit anderen Spielern gibt es eine weitere Möglichkeit: Beim Händler jeder Stadt warten Reisende, die dich mit 20 Dukaten belohnen, wenn du sie sicher in ihre Wunschstadt begleitest.</p></div>
  </details>
  <details>
    <summary>Warum steigt mein Skill „Magic Resistance“ nicht?</summary>
    <div class="faq__answer"><p>Dieser Skill ist im aktuellen System deaktiviert.</p></div>
  </details>
  <details>
    <summary>Ich bin gestorben! Und jetzt?</summary>
    <div class="faq__answer"><p>Mit jedem Tod verlängert sich deine Wartezeit als Geist um 20 Sekunden. Keine Sorge: Nach einer Weile wird sie wieder auf 20 Sekunden zurückgesetzt. Überlege dir trotzdem gut, wohin du dich wagst – sonst sind Wartezeiten von mehreren Minuten keine Seltenheit. Und gerate nicht gleich in Panik, sondern probiere in Ruhe aus, wie du dich am besten aus so einer Lage befreist.</p></div>
  </details>
  <details>
    <summary>Ich habe genug Geld auf der Bank, aber der Händler verkauft mir nichts?</summary>
    <div class="faq__answer"><p>Die Händler auf Nebelland nehmen keine „Kreditkarten“. Wie jeder andere auch möchten sie ihr Geld bar auf die Hand – hol dein Gold also vorher von der Bank.</p></div>
  </details>
  <details>
    <summary>Welche Befehle kann ich benutzen?</summary>
    <div class="faq__answer"><p>Die wichtigsten Befehle findest du in den <a href="<?php echo e(url('1schritte')); ?>#commands">Ersten Schritten</a>, die Zauberbefehle im <a href="<?php echo e(url('zauber')); ?>">Zauberbuch</a>.</p></div>
  </details>
