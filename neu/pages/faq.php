<div class="ui-text">
  <h2>Häuser &amp; Hausmenü</h2>
</div>
<div class="faq">
  <details>
    <summary>Wo finde ich die Häuserpreise?</summary>
    <div class="faq__answer"><p>In der <a href="<?php echo e(url('haus')); ?>">Häuserliste</a>, sortiert nach Städten. Die angegebenen Preise gelten pro Tag; die Hausnummern helfen dir, das richtige Haus zu finden.</p></div>
  </details>
  <details>
    <summary>Wie bekomme ich ein Haus?</summary>
    <div class="faq__answer"><p>Hast du dir ein Haus ausgesucht, rufst du per Page einen GM, der es dir übergibt. Als Kaution zahlst du zwei Wochenmieten; du erhältst sie bei Auszug oder Umzug zurück.</p></div>
  </details>
  <details>
    <summary>Wozu dient das Hausmenü?</summary>
    <div class="faq__answer">
      <p>Mit dem Hausmenü richtest du dein Haus selbst ein. Drei Dinge solltest du dabei beachten:</p>
      <ol>
        <li>Alles, was nicht verfallen soll, sofort festschrauben. Die übrigen Funktionen des Hausmenüs lassen sich auch bei festgeschraubten Gegenständen nutzen.</li>
        <li>Verschiebst du etwas zu hoch oder zu tief, kommst du selbst nicht mehr heran und musst einen GM bemühen.</li>
        <li>Schließ deine Haustüren unbedingt ab. Hast du über das Hausmenü einen Schlüssel angefertigt, genügt es, ihn im Rucksack zu tragen – das ständige Auf- und Zuschließen entfällt.</li>
      </ol>
    </div>
  </details>
  <details>
    <summary>Was passiert, wenn ich die Miete nicht zahlen kann?</summary>
    <div class="faq__answer"><p>Nach drei Wochen unbezahlter Miete wird das Haus automatisch gepfändet. Ein GM räumt es anschließend aus und übergibt alles dem Stadtrat. Dort kannst du deine Schulden begleichen und mit etwas Glück deine Habseligkeiten auslösen.</p></div>
  </details>
</div>

