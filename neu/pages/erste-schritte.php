  <h2 id="anmeldung">1. Wie melde ich mich an?</h2>
  <p>Einen Account auf Nebelland bekommst du über ICQ. Trag einfach deine ICQ-Nummer in unser <a href="<?php echo e(url('anmeldung')); ?>">Anmeldeformular</a> ein. Innerhalb eines Tages meldet sich dann jemand aus dem Team zu einem kurzen Gespräch. Keine Angst – wir fragen weder Regeln noch sonst etwas ab.</p>

  <h2 id="spiel">2. Wie komme ich ins Spiel?</h2>
  <p>Um auf Nebelland zu spielen, brauchst du Ultima Online. Dein Client muss mindestens <strong>Version 4</strong> haben.</p>
  <ul>
    <li><strong>Age of Shadows (empfohlen):</strong> Der AoS-Client liegt bereits in Version 4 vor und muss nicht mehr mit UOPatch aktualisiert werden.</li>
    <li><strong>Renaissance, The Second Age (T2A) oder Lord Blackthorn’s Revenge (LBR):</strong> Hier musst du UOPatch ausführen. Einen Version-4-Client einfach von woanders zu kopieren, reicht nicht aus – UOPatch aktualisiert auch wichtige Cliloc-Übersetzungen, die für das Spiel nötig sind.</li>
  </ul>
  <p>Meldet UOPatch einen Fehler, liegen in deinem UO-Verzeichnis vermutlich bereits veränderte Dateien, etwa von anderen Freeshards. Deinstalliere UO dann vollständig, lösche auch den UO-Ordner von Hand und installiere das Spiel neu. Führe direkt danach UOPatch aus – bei einer frischen Installation startet er auch automatisch mit dem Spiel.</p>
  <p>Ist dein Client auf Version 4, installierst du als Nächstes die Nebelland-Dateien. Am bequemsten geht das mit dem <a href="<?php echo e(url('files')); ?>">Nebelland-Patcher</a>, der dich auch künftig automatisch auf dem neuesten Stand hält. Lass beim Einspielen alle vorhandenen Dateien überschreiben, sonst kommt es im Spiel zu Darstellungsfehlern.</p>
  <p>Geschafft? Bestens – dann kann es fast losgehen! Starte die <strong>Nebelland.exe</strong> in deinem UO-Verzeichnis, gib in der Anmeldemaske deine Account-Daten ein und klicke auf den Weiter-Pfeil. Schon kannst du deinen ersten Charakter erstellen.</p>

  <h2 id="erstellung">3. Einen Charakter erstellen</h2>
  <p>Klicke auf <strong>„New“</strong> und gib oben den Namen deines Charakters ein. Bitte beachte dabei unsere <a href="<?php echo e(url('regeln')); ?>#r2">Namensregeln</a>. Unter dem Porträt wählst du das Geschlecht, links daneben Frisur und Bart, rechts Hautfarbe und die Farbe deiner Startkleidung. Je nach Volk, das du später wählst, kann sich das Aussehen noch etwas verändern.</p>
  <p>Ein Klick auf Weiter führt dich zu den Fähigkeiten. <strong>Wichtig ist hier nur die Verteilung von Stärke (STR), Geschicklichkeit (DEX) und Intelligenz (INT)</strong> – deine Skills wählst du später im Spiel. Die anschließend angezeigte Landkarte kannst du getrost ignorieren und direkt weiterklicken.</p>

  <h2 id="geburt">4. Im Geburtenraum</h2>
  <p>Nun bist du in der Welt angekommen – ganz fertig ist dein Charakter aber noch nicht. Im Geburtenraum vervollständigst du ihn Schritt für Schritt. Folge dabei einfach den Wegweisern und durchschreite die passenden Tore.</p>

