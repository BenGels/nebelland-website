  <h2 id="tipps">5. Tipps für Neulinge</h2>

  <h3>Wenig Gold – und alles so teuer?</h3>
  <p>Ja, du startest mit nur 300 Dukaten. Bedenke aber: Gold ist auf Nebelland ein Vielfaches mehr wert als auf anderen Shards. Alle haben weniger davon, und entsprechend günstig sollten auch die Waren der Handwerker sein. Es gibt nur wenige Händler (Vendoren), und die verlangen gesalzene Preise. Kauf dort nur das Nötigste – Handwerker aus der Spielerschaft sind deutlich günstiger.</p>

  <h3>Kein Gold in Monstern?</h3>
  <p>Richtig, mit wenigen Ausnahmen tragen Monster bei uns kein Gold bei sich – oder hast du schon einmal einen Schleim mit Geldbeutel gesehen? Stattdessen stehen in der Nähe vieler Spawns Metalltruhen, die du mit Dietrichen vom Händler öffnen kannst. Ausnahmen sind einige stärkere Monster und die Banditen: Sie hausen in einer Festung westlich von Dreibrücken, der Stadt der Menschen, und tragen Gold bei sich – für Neulinge ein lohnendes Ziel. Weitere gute Anlaufstellen sind die Kanalisation von Dreibrücken, die du durch einen Keller im südlichen Armenviertel erreichst, und der Dungeon am Ausgang der Zwergenbinge in Richtung Sehdorf.</p>

  <h3>Was kauft der geizige Händler?</h3>
  <p>In jeder Stadt gibt es genau einen Händler, und der ist entsprechend knauserig: Er zahlt wenig und verlangt viel. Für Handwerker ist er in der Not dennoch die Rettung. Was er ankauft, ändert sich regelmäßig – meist sind es einfache Gegenstände, damit sich Handwerker in schweren Anfangszeiten über Wasser halten können.</p>

  <h3>Reisende begleiten</h3>
  <p>Wer Gold verdienen will, ohne ständig Monster zu erschlagen, kann Reisende (Escorts) von Stadt zu Stadt begleiten. Etwa alle zwei Stunden warten sie beim Händler auf Geleit und zahlen dafür 20 Dukaten.</p>

  <h3>Die Bank ist kein Lagerhaus</h3>
  <p>Den Bankier sprichst du mit einem Satz an, der das Wort „Bank“ enthält. Bei ihm kannst du allerdings nur Gold lagern. Für Gegenstände gibt es mietbare Truhen – wende dich dafür an das Team oder die Stadtverwaltung.</p>

